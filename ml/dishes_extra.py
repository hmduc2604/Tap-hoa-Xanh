"""Món ăn bổ sung cho trợ lý (cùng định dạng với DISHES trong knowledge.py), viết bằng cú pháp ngắn.

Mỗi nguyên liệu là một chuỗi:  "nhãn[=từ khóa không dấu] [số lượng]"
  "ba rọi 150g"      150 g cho mỗi người (từ khóa tự suy ra từ nhãn: "ba roi")
  "trứng gà x2"      2 quả cho mỗi người
  "nước mắm *"       gia vị dùng sẵn trong bếp: chỉ cần 1 đơn vị, hiển thị sau cùng
  "lá chanh -"       cửa hàng không bán, báo là "cần mua thêm ở nơi khác"
  "thịt vai=than heo 150g"   khi nhãn hiển thị khác từ khóa tìm trong danh mục
Từ khóa được tra trong danh mục đang bán, không gắn cứng sản phẩm. Từ khóa nên có từ phân biệt ("tôm sú", "cá hồi") để
không khớp nhầm hàng khác; khi hai sản phẩm cùng khớp thì sản phẩm bán chạy hơn được chọn.
"""
import re

from common.utils import strip_accents

_ING = re.compile(r"^(?P<label>[^=]+?)(?:=(?P<kw>[a-z0-9 ]+?))?(?:\s+(?:(?P<g>\d+)g|x(?P<pcs>\d+(?:\.\d+)?)|(?P<flag>[*\-])))?$")


def ingredient(spec, labels):
    m = _ING.match(spec.strip())
    if not m:
        raise ValueError(f"nguyên liệu sai cú pháp: {spec!r}")
    label = m["label"].strip()
    kw = m["kw"] or strip_accents(label)
    out = {"kw": kw}
    if m["g"]:
        out["g"] = int(m["g"])
    elif m["pcs"]:
        out["pcs"] = float(m["pcs"]) if "." in m["pcs"] else int(m["pcs"])
    elif m["flag"] == "*":
        out["pantry"] = True
    elif m["flag"] == "-":
        out["missing"] = True
    if labels.setdefault(kw, label) != label and not m["kw"]:
        pass  # cùng từ khóa, hai cách gọi: giữ cách gọi đầu tiên
    return out


def build(rows, labels):
    dishes = []
    for name, aliases, meals, ings, how in rows:
        dish = {"name": name, "aliases": aliases, "meals": meals.split(), "ingredients": [ingredient(i, labels) for i in ings]}
        if how:
            dish["how"] = how
        dishes.append(dish)
    return dishes


